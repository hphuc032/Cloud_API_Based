"""Turn a reviewed pip resolution report into the Docker target's hash lock.

Resolve CPython 3.11 wheels with both backend requirements inputs and
`pip install --dry-run --ignore-installed --report REPORT ...`. Supply one report
per supported Linux architecture. Cross-resolution must constrain all versions
to the first report; the generator rejects different package/version sets.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
from urllib.parse import unquote, urlsplit


def packages_from_report(report, architecture):
    # pip's cross-platform report describes its host in "environment". Inspect
    # the actual selected wheel tags as well, rather than trusting that host.
    if report['environment']['platform_system'] != 'Linux':
        raise ValueError('Resolve using a Linux pip host')
    packages = {}
    for item in report['install']:
        name = re.sub(r'[-_.]+', '-', item['metadata']['name']).lower()
        version = item['metadata']['version']
        download = item['download_info']
        digest = download['archive_info']['hashes']['sha256']
        filename = unquote(urlsplit(download['url']).path.rsplit('/', 1)[-1])
        if (not re.fullmatch(r'[a-z0-9][a-z0-9-]*', name) or
                not re.fullmatch(r'[a-zA-Z0-9.!+_-]+', version) or
                not re.fullmatch(r'[a-f0-9]{64}', digest) or
                not filename.endswith('.whl') or name in packages):
            raise ValueError('Invalid, duplicate or non-wheel resolution entry')
        _, python_tag, abi, platform = filename[:-4].rsplit('-', 3)
        if platform != 'any':
            if (not all(tag.startswith('manylinux') and tag.endswith('_'+architecture)
                        for tag in platform.split('.')) or
                    not re.fullmatch(r'cp3(?:[2-9]|10|11)', python_tag) or
                    abi not in ('abi3', 'cp311') or
                    (abi == 'cp311' and python_tag != 'cp311')):
                raise ValueError('Unexpected CPython 3.11 Linux wheel: '+filename)
        packages[name] = (version, digest)
    if not packages:
        raise ValueError('Empty resolution report')
    return packages


def render(report, inputs, arm64_report):
    packages = packages_from_report(report, 'x86_64')
    arm64 = packages_from_report(arm64_report, 'aarch64')
    if {n:v[0] for n,v in packages.items()} != {n:v[0] for n,v in arm64.items()}:
        raise ValueError('Architecture reports must resolve identical package/version sets')
    lines = ['# Linux amd64/arm64 CPython 3.11 wheels; generated by docker/lock_requirements.py.',
             '# Install with --require-hashes --only-binary=:all:.']
    for path in inputs:
        # Git checkouts may translate LF to CRLF. Fingerprint canonical text so
        # the same inputs regenerate the same lock on Windows and Linux.
        canonical = path.read_text().replace('\r\n', '\n').encode('utf-8')
        lines.append('# Input '+path.name+' LF-normalized SHA256 '+hashlib.sha256(canonical).hexdigest())
    for path in inputs:
        for line in path.read_text().splitlines():
            line = line.partition('#')[0].strip()
            if not line:
                continue
            pin = re.fullmatch(r'([a-zA-Z0-9_.-]+)(?:\[[a-zA-Z0-9_,.-]+\])?==([a-zA-Z0-9.!+_-]+)', line)
            if not pin:
                raise ValueError('Inputs must contain reviewed exact package pins')
            name = re.sub(r'[-_.]+', '-', pin[1]).lower()
            if packages.get(name, ('', ''))[0] != pin[2]:
                raise ValueError('Resolution report does not match input pin: '+name)
    for name, (version, digest) in sorted(packages.items()):
        hashes = sorted({digest, arm64[name][1]})
        lines.append(name+'=='+version+''.join(' --hash=sha256:'+h for h in hashes))
    return '\n'.join(lines)+'\n'


if __name__ == '__main__':
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--report', type=Path, required=True)
    parser.add_argument('--arm64-report', type=Path, required=True)
    parser.add_argument('--output', type=Path, default=root/'backend/requirements.lock')
    args = parser.parse_args()
    inputs = [root/'backend/requirements.txt', root/'backend/build-requirements.txt']
    args.output.write_text(render(json.loads(args.report.read_text()), inputs,
                                 json.loads(args.arm64_report.read_text())), newline='\n')
